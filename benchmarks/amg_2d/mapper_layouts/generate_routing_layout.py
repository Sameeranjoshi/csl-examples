import numpy as np

def generate_csl(layout_config, kernel_name="pe_program.csl", filename="generated_layout.csl"):
    kernel_x_dim = layout_config["kernel_x_dim"]
    kernel_y_dim = layout_config["kernel_y_dim"]
    M = layout_config["M"]
    N = layout_config["N"]

    with open(filename, "w") as f:
        # Write params
        f.write("// AUTOGENERATED DO NOT EDIT\n")
        f.write(f"param kernel_x_dim: i16 = {kernel_x_dim};\n")
        f.write(f"param kernel_y_dim: i16 = {kernel_y_dim};\n")
        f.write(f"param M: i16 = {layout_config['M']};\n")
        f.write(f"param N: i16 = {layout_config['N']};\n\n")

        # Colors definitions
        f.write("// Colors\n")
        f.write("const ax_color_1: color = @get_color(0);\n")
        f.write("const ax_color_2: color = @get_color(1);\n")
        f.write("const x_color: color = @get_color(2);\n\n")

        f.write('const memcpy = @import_module("<memcpy/get_params>", .{\n')
        f.write(f"  .width = kernel_x_dim,\n")
        f.write(f"  .height = kernel_y_dim\n")
        f.write("});\n\n")

        f.write("layout {\n")
        f.write("  @set_rectangle(kernel_x_dim, kernel_y_dim);\n\n")

        f.write("  @comptime_assert(M % kernel_y_dim == 0);\n")
        f.write("  @comptime_assert(N % kernel_x_dim == 0);\n\n")

        f.write("  const common_params = .{\n")
        f.write("    .M_per_PE = M / kernel_y_dim,\n")
        f.write("    .N_per_PE = N / kernel_x_dim,\n")
        f.write("    .kernel_x_dim = kernel_x_dim,\n")
        f.write("    .kernel_y_dim = kernel_y_dim,\n")
        f.write("    .x_color = x_color\n")
        f.write("  };\n\n")

        f.write("  const even_params = @concat_structs(common_params, .{\n")
        f.write("    .send_east_color = ax_color_1, .recv_west_color = ax_color_2\n")
        f.write("  });\n\n")

        f.write("  const odd_params = @concat_structs(common_params, .{\n")
        f.write("    .send_east_color = ax_color_2, .recv_west_color = ax_color_1\n")
        f.write("  });\n\n")

        # Set PE tile codes
        for pe_x in range(kernel_x_dim):
            for pe_y in range(kernel_y_dim):
                param_choice = "even_params" if pe_x % 2 == 0 else "odd_params"
                f.write(f"  @set_tile_code({pe_x}, {pe_y}, \"{kernel_name}\", @concat_structs(\n")
                f.write(f"    .{{ .memcpy_params = memcpy.get_params({pe_x}) }}, {param_choice}));\n")

        f.write("\n  // Define routes\n")
        f.write("  const RX_R_TX_RS = .{ .rx = .{RAMP},  .tx = .{RAMP, SOUTH} };\n")
        f.write("  const RX_N_TX_RS = .{ .rx = .{NORTH}, .tx = .{RAMP, SOUTH} };\n")
        f.write("  const RX_N_TX_R  = .{ .rx = .{NORTH}, .tx = .{RAMP} };\n")
        f.write("  const RX_W_TX_R  = .{ .rx = .{WEST},  .tx = .{RAMP} };\n")
        f.write("  const RX_R_TX_E  = .{ .rx = .{RAMP},  .tx = .{EAST} };\n\n")

        for pe_x in range(kernel_x_dim):
            for pe_y in range(kernel_y_dim):
                # X routing
                if pe_y == 0:
                    f.write(f"  @set_color_config({pe_x}, {pe_y}, x_color, .{{ .routes = RX_R_TX_RS }});\n")
                elif pe_y == kernel_y_dim - 1:
                    f.write(f"  @set_color_config({pe_x}, {pe_y}, x_color, .{{ .routes = RX_N_TX_R }});\n")
                else:
                    f.write(f"  @set_color_config({pe_x}, {pe_y}, x_color, .{{ .routes = RX_N_TX_RS }});\n")

                # Ax routing
                if pe_x % 2 == 0:
                    f.write(f"  @set_color_config({pe_x}, {pe_y}, ax_color_1, .{{ .routes = RX_R_TX_E }});\n")
                    f.write(f"  @set_color_config({pe_x}, {pe_y}, ax_color_2, .{{ .routes = RX_W_TX_R }});\n")
                else:
                    f.write(f"  @set_color_config({pe_x}, {pe_y}, ax_color_1, .{{ .routes = RX_W_TX_R }});\n")
                    f.write(f"  @set_color_config({pe_x}, {pe_y}, ax_color_2, .{{ .routes = RX_R_TX_E }});\n")

        f.write('\n  // export symbol names\n')
        f.write('  @export_name("A", [*]f32, true);\n')
        f.write('  @export_name("x", [*]f32, true);\n')
        f.write('  @export_name("y", [*]f32, true);\n')
        f.write('  @export_name("compute", fn()void);\n')

        f.write('}\n')

    print(f"Generated CSL file: {filename}")

if __name__ == "__main__":
    layout_config = {
        "kernel_x_dim": 2,
        "kernel_y_dim": 2,
        "M": 4,
        "N": 4
    }

    generate_csl(layout_config)
