#!/usr/bin/env python3
"""
generate_poisson.py

Generates the matrix-market file for the 3D 7-point Poisson (Dirichlet)
discretization on a regular cubic grid of size nx * ny * nz.

Usage:
  python3 generate_poisson.py --nx 200 --ny 200 --nz 400 -o poisson_200x200x400.mtx

This writes the sparse matrix in Matrix Market (coordinate) format.
"""
import argparse
import sys
import numpy as np

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--nx", type=int, required=True)
    parser.add_argument("--ny", type=int, required=True)
    parser.add_argument("--nz", type=int, required=True)
    parser.add_argument("-o", "--output", required=True)
    args = parser.parse_args()

    nx, ny, nz = args.nx, args.ny, args.nz
    N = nx * ny * nz
    print(f"Generating 3D Poisson ({nx}x{ny}x{nz}) -> {N} unknowns")

    # Helper to convert (i,j,k) -> index
    def idx(i,j,k):
        return (k*ny + j) * nx + i

    rows = []
    cols = []
    vals = []

    for k in range(nz):
        for j in range(ny):
            for i in range(nx):
                r = idx(i,j,k)
                diag = 0.0
                # center
                diag += 6.0
                rows.append(r+1); cols.append(r+1); vals.append(6.0)  # 1-based for .mtx

                # neighbors (Dirichlet: omit neighbors outside domain)
                if i-1 >= 0:
                    rows.append(r+1); cols.append(idx(i-1,j,k)+1); vals.append(-1.0)
                if i+1 < nx:
                    rows.append(r+1); cols.append(idx(i+1,j,k)+1); vals.append(-1.0)
                if j-1 >= 0:
                    rows.append(r+1); cols.append(idx(i,j-1,k)+1); vals.append(-1.0)
                if j+1 < ny:
                    rows.append(r+1); cols.append(idx(i,j+1,k)+1); vals.append(-1.0)
                if k-1 >= 0:
                    rows.append(r+1); cols.append(idx(i,j,k-1)+1); vals.append(-1.0)
                if k+1 < nz:
                    rows.append(r+1); cols.append(idx(i,j,k+1)+1); vals.append(-1.0)

    nnz = len(rows)
    print(f"Writing {nnz} nonzeros to {args.output} ...")

    with open(args.output, "w") as f:
        f.write("%%MatrixMarket matrix coordinate real general\n")
        f.write(f"% Generated by generate_poisson.py\n")
        f.write(f"{N} {N} {nnz}\n")
        for r,c,v in zip(rows, cols, vals):
            f.write(f"{r} {c} {v:.16g}\n")

    print("Done.")

if __name__ == "__main__":
    main()
